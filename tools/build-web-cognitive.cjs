// The browser executes the exact pure task modules used by the miniprogram.
const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto');
const root=path.resolve(__dirname,'..'),names=['cognitive-config','gonogo-test','stroop-test','flanker-test','nback-test','trail-test','digit-span-test'];
const chunks=['/* Generated by tools/build-web-cognitive.cjs. Edit the shared source modules, then rebuild. */','(() => {\n\'use strict\'; const tasks = {};'];
for(const name of names){const source=fs.readFileSync(path.join(root,'miniprogram/utils',name+'.js'),'utf8');
 if(/\brequire\s*\(/.test(source))throw Error('Task must remain a pure standalone module: '+name);
 const digest=crypto.createHash('sha256').update(source).digest('hex');
 chunks.push(`// ${name} sha256=${digest}\ntasks[${JSON.stringify(name)}] = (() => { const module = {exports:{}};\n${source}\nreturn Object.freeze(module.exports); })();`);}
chunks.push('window.FrozenCognitive = Object.freeze(tasks);\n})();\n');
fs.writeFileSync(path.join(root,'patient-web/js/cognitive-shared.js'),chunks.join('\n'),'utf8');
console.log('Bundled '+names.length+' exact shared modules.');
